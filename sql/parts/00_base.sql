create extension if not exists pgcrypto;

-- ---------- staff: one row per person who has signed in (made automatically at their first sign-in) ----------
create table if not exists public.profiles (
    id          uuid primary key references auth.users (id) on delete cascade,
    email       text,
    full_name   text,
    avatar_url  text,
    approved    boolean not null default false,          -- an admin approves staff (or pre-approves the email)
    role        text not null default 'technician',      -- 'technician' or 'admin'
    created_at  timestamptz not null default now()
);
create index if not exists profiles_email_idx on public.profiles (lower(email));

-- emails an admin has approved before the person first signs in
create table if not exists public.allowed_emails (
    email     text primary key,
    role      text not null default 'technician',
    added_at  timestamptz not null default now(),
    added_by  text
);

-- first sign-in: make the person's profile; approved straight away if an admin pre-approved the email
create or replace function public.pestis_handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare a public.allowed_emails;
begin
    select * into a from public.allowed_emails where lower(email) = lower(new.email);
    insert into public.profiles (id, email, full_name, avatar_url, approved, role)
    values (new.id, lower(new.email),
            coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1)),
            new.raw_user_meta_data ->> 'avatar_url',
            a.email is not null, coalesce(a.role, 'technician'))
    on conflict (id) do nothing;
    return new;
end $$;
drop trigger if exists pestis_on_auth_user_created on auth.users;
create trigger pestis_on_auth_user_created after insert on auth.users
    for each row execute function public.pestis_handle_new_user();

-- ---------- sites ----------
create table if not exists public.clients (
    id          bigint generated by default as identity primary key,
    "Name"      text not null,
    "Address"   text,
    "Contact"   text,
    "Email"     text,
    "Notes"     text,
    created_at  timestamptz not null default now()
);

-- ---------- service records (one row per station check, plus visit summaries and other events) ----------
create table if not exists public.service_logs (
    id             bigint generated by default as identity primary key,
    client_id      bigint not null references public.clients (id) on delete cascade,
    barcode_id     text not null,
    payload        jsonb not null default '{}'::jsonb,
    created_at     timestamptz not null default now(),
    technician_id  uuid default auth.uid()
);
create index if not exists service_logs_client_idx on public.service_logs (client_id, created_at);
create index if not exists service_logs_barcode_idx on public.service_logs (client_id, barcode_id);

-- ---------- who can do what (the later files add a restrictive safety net on top) ----------
create or replace function public.pestis_is_approved()
returns boolean language sql security definer stable set search_path = public as $$
    select exists (select 1 from public.profiles where id = auth.uid() and approved);
$$;
create or replace function public.pestis_is_admin()
returns boolean language sql security definer stable set search_path = public as $$
    select exists (select 1 from public.profiles where id = auth.uid() and approved and role = 'admin');
$$;

alter table public.profiles       enable row level security;
alter table public.allowed_emails enable row level security;
alter table public.clients        enable row level security;
alter table public.service_logs   enable row level security;

drop policy if exists "Profiles: read"           on public.profiles;
drop policy if exists "Profiles: change own"     on public.profiles;
drop policy if exists "Profiles: admins change"  on public.profiles;
drop policy if exists "Profiles: admins remove"  on public.profiles;
create policy "Profiles: read"          on public.profiles for select to authenticated using (id = auth.uid() or public.pestis_is_approved());
create policy "Profiles: change own"    on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
create policy "Profiles: admins change" on public.profiles for update to authenticated using (public.pestis_is_admin()) with check (public.pestis_is_admin());
create policy "Profiles: admins remove" on public.profiles for delete to authenticated using (public.pestis_is_admin());

drop policy if exists "Allowed emails: admins" on public.allowed_emails;
create policy "Allowed emails: admins" on public.allowed_emails for all to authenticated using (public.pestis_is_admin()) with check (public.pestis_is_admin());

drop policy if exists "Sites: staff" on public.clients;
create policy "Sites: staff" on public.clients for all to authenticated using (public.pestis_is_approved()) with check (public.pestis_is_approved());

drop policy if exists "Records: staff" on public.service_logs;
create policy "Records: staff" on public.service_logs for all to authenticated using (public.pestis_is_approved()) with check (public.pestis_is_approved());

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.profiles, public.allowed_emails, public.clients, public.service_logs to authenticated;
grant usage, select on all sequences in schema public to authenticated;
revoke all on public.profiles, public.allowed_emails, public.clients, public.service_logs from anon;

notify pgrst, 'reload schema';
