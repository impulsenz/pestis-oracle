    from logs l
    where barcode_id not in ('SITE_VISIT_SUMMARY', 'REC_UPDATE', 'SITE_MAP', 'MAP_PIN', 'BARCODE_CHANGE', 'SITE_CHANGE')
      and cid is not null
      and not exists (select 1 from replaced r where r.ref = l.p->>'clientRef')
      and (
          coalesce(p->>'recommendation', p->>'recommendationNote', '') <> ''
          or coalesce(p->>'photo', '') <> ''
          or (case when jsonb_typeof(p->'photos') = 'array' then jsonb_array_length(p->'photos') > 0 else false end)
      )
),
latest as (
    select distinct on (rkey) * from rec_rows order by rkey, created_at desc
),
firsts as (
    select rkey, min(created_at) as first_at from rec_rows group by rkey
),
old_recs as (
select l.rkey as id,
       case when (l.p->>'recNo') ~ '^[0-9]+$' then (l.p->>'recNo')::bigint end as rec_no,
       l.cid as client_id,
       l.barcode_id as station_barcode,
       l.p->>'locationName' as station_name,
       l.p->>'deviceType' as station_type,
       l.rtext as text,
       case when jsonb_typeof(l.p->'photos') = 'array' and jsonb_array_length(l.p->'photos') > 0 then l.p->'photos'
            when coalesce(l.p->>'photo', '') <> '' then jsonb_build_array(l.p->>'photo')
            else '[]'::jsonb end as photos,
       coalesce(
           case when coalesce(l.p->>'recCreatedAt', '') ~ '^\d{4}-\d{2}-\d{2}T' then (l.p->>'recCreatedAt')::timestamptz end,
           case when coalesce(l.p->>'servicedAt', '') ~ '^\d{4}-\d{2}-\d{2}T' then (l.p->>'servicedAt')::timestamptz end,
           f.first_at) as raised_at,
       l.p->>'technician' as raised_by,
       f.first_at as created_at
from latest l join firsts f using (rkey)
)
insert into public.recommendations (id, client_id, station_barcode, station_name, station_type, text, photos, raised_at, raised_by, created_at)
select id, client_id, station_barcode, station_name, station_type, text, photos, raised_at, raised_by, created_at
from old_recs o
where not exists (select 1 from public.recommendations r where r.id = o.id)
order by raised_at, id
on conflict (id) do nothing;

-- ---------------------------------------------------------------
-- 4. Status kept up to date from the app's recommendation updates
--    (each update is still logged in service_logs as a REC_UPDATE record)
-- ---------------------------------------------------------------
create or replace function public.pestis_apply_rec_update()
returns trigger language plpgsql security definer set search_path = public as $$
declare
    p jsonb := new.payload::jsonb;
    st text;
begin
    if new.barcode_id <> 'REC_UPDATE' or p is null or coalesce(p->>'recRef', '') = '' then return new; end if;
    st := case when p->>'status' = 'new' then 'open' else p->>'status' end;
    if st not in ('open', 'pending', 'complete') then st := 'pending'; end if;
    update public.recommendations
       set status = st,
           completed_at = case when st = 'complete' then now() else null end,
           updated_at = now()
     where id = p->>'recRef';
    return new;
end $$;
drop trigger if exists pestis_apply_rec_update on public.service_logs;
create trigger pestis_apply_rec_update after insert on public.service_logs
    for each row execute function public.pestis_apply_rec_update();

-- Bring existing statuses in line with the updates already logged
with last_update as (
    select distinct on (payload::jsonb->>'recRef')
           payload::jsonb->>'recRef' as rid,
           case when payload::jsonb->>'status' = 'new' then 'open' else payload::jsonb->>'status' end as st,
           coalesce(case when coalesce(payload::jsonb->>'servicedAt', '') ~ '^\d{4}-\d{2}-\d{2}T' then (payload::jsonb->>'servicedAt')::timestamptz end, created_at) as at
    from public.service_logs
    where barcode_id = 'REC_UPDATE' and coalesce(payload::jsonb->>'recRef', '') <> ''
    order by payload::jsonb->>'recRef', created_at desc
)
update public.recommendations r
   set status = case when u.st in ('open', 'pending', 'complete') then u.st else 'pending' end,
       completed_at = case when u.st = 'complete' then u.at else null end
  from last_update u
 where r.id = u.rid;

notify pgrst, 'reload schema';
