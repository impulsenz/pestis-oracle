-- Pestis: recommendations get their own table.
--   * Each recommendation is one row with a number the database gives it (R-0001, R-0002 ...).
--   * Existing recommendations are copied in (keeping any number they already had), oldest first.
--   * Status changes made in the app keep this table's status up to date.
-- Run once in Supabase -> SQL Editor (after pestis_r14_update.sql if you ran that). Safe to run again.

-- Times written the way the database API returns them (so ids match what the app sees)
set timezone = 'UTC';

-- Helper used by the policies (same as in earlier scripts)
create or replace function public.pestis_is_approved()
returns boolean language sql security definer stable set search_path = public as $$
    select exists (select 1 from public.profiles where id = auth.uid() and approved);
$$;
revoke all on function public.pestis_is_approved() from public;
grant execute on function public.pestis_is_approved() to authenticated;

-- ---------------------------------------------------------------
-- 1. The table
-- ---------------------------------------------------------------
create table if not exists public.recommendations (
    id              text primary key,                                  -- made by the app, so it works offline
    rec_no          bigint generated by default as identity unique,    -- the R-number
    client_id       text not null,                                     -- the site (clients.id)
    station_barcode text,
    station_name    text,
    station_type    text,
    text            text not null default '',
    photos          jsonb not null default '[]'::jsonb,                -- storage paths in the station-photos bucket
    status          text not null default 'open' check (status in ('open', 'pending', 'complete')),
    raised_at       timestamptz not null default now(),                -- when it was raised on site
    raised_by       text,
    raised_by_id    uuid default auth.uid(),
    completed_at    timestamptz,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now()
);
create index if not exists recommendations_client_idx on public.recommendations (client_id);
create index if not exists recommendations_status_idx on public.recommendations (status);

alter table public.recommendations enable row level security;
drop policy if exists "Approved staff read recommendations"   on public.recommendations;
drop policy if exists "Approved staff add recommendations"    on public.recommendations;
drop policy if exists "Approved staff update recommendations" on public.recommendations;
drop policy if exists "Approved staff delete recommendations" on public.recommendations;
create policy "Approved staff read recommendations"   on public.recommendations for select to authenticated using (public.pestis_is_approved());
create policy "Approved staff add recommendations"    on public.recommendations for insert to authenticated with check (public.pestis_is_approved());
create policy "Approved staff update recommendations" on public.recommendations for update to authenticated using (public.pestis_is_approved()) with check (public.pestis_is_approved());
create policy "Approved staff delete recommendations" on public.recommendations for delete to authenticated using (public.pestis_is_approved());
grant select, insert, update, delete on public.recommendations to authenticated;

-- ---------------------------------------------------------------
-- 2. The earlier numbering trigger on service_logs is no longer used
-- ---------------------------------------------------------------
drop trigger if exists pestis_assign_rec_no on public.service_logs;

-- ---------------------------------------------------------------
-- 3. Copy the recommendations already recorded in service_logs
--    (the latest version of each; ones replaced by a later save are skipped)
-- ---------------------------------------------------------------
-- a) ones that already have a number keep it
with logs as (
    select client_id::text as cid, barcode_id, created_at, payload::jsonb as p
    from public.service_logs
    where payload is not null
),
replaced as (
    select distinct p->>'supersedes' as ref from logs where p ? 'supersedes'
),
rec_rows as (
    select l.*,
           coalesce(p->>'recRef', p->>'clientRef', barcode_id || '@' || (to_json(created_at) #>> '{}')) as rkey,  -- same id the app uses
           coalesce(nullif(p->>'recommendation', ''), nullif(p->>'recommendationNote', ''), 'Issue photo attached') as rtext
    from logs l
    where barcode_id not in ('SITE_VISIT_SUMMARY', 'REC_UPDATE', 'SITE_MAP', 'MAP_PIN', 'BARCODE_CHANGE', 'SITE_CHANGE')
      and cid is not null
      and not exists (select 1 from replaced r where r.ref = l.p->>'clientRef')
      and (
          coalesce(p->>'recommendation', p->>'recommendationNote', '') <> ''
          or coalesce(p->>'photo', '') <> ''
          or (case when jsonb_typeof(p->'photos') = 'array' then jsonb_array_length(p->'photos') > 0 else false end)
      )
),
latest as (
    select distinct on (rkey) * from rec_rows order by rkey, created_at desc
),
firsts as (
    select rkey, min(created_at) as first_at from rec_rows group by rkey
),
old_recs as (
select l.rkey as id,
       case when (l.p->>'recNo') ~ '^[0-9]+$' then (l.p->>'recNo')::bigint end as rec_no,
       l.cid as client_id,
       l.barcode_id as station_barcode,
       l.p->>'locationName' as station_name,
       l.p->>'deviceType' as station_type,
       l.rtext as text,
       case when jsonb_typeof(l.p->'photos') = 'array' and jsonb_array_length(l.p->'photos') > 0 then l.p->'photos'
            when coalesce(l.p->>'photo', '') <> '' then jsonb_build_array(l.p->>'photo')
            else '[]'::jsonb end as photos,
       coalesce(
           case when coalesce(l.p->>'recCreatedAt', '') ~ '^\d{4}-\d{2}-\d{2}T' then (l.p->>'recCreatedAt')::timestamptz end,
           case when coalesce(l.p->>'servicedAt', '') ~ '^\d{4}-\d{2}-\d{2}T' then (l.p->>'servicedAt')::timestamptz end,
           f.first_at) as raised_at,
       l.p->>'technician' as raised_by,
       f.first_at as created_at
from latest l join firsts f using (rkey)
)
insert into public.recommendations (id, rec_no, client_id, station_barcode, station_name, station_type, text, photos, raised_at, raised_by, created_at)
overriding system value
select id, rec_no, client_id, station_barcode, station_name, station_type, text, photos, raised_at, raised_by, created_at
from old_recs o
where rec_no is not null and not exists (select 1 from public.recommendations r where r.rec_no = o.rec_no)
on conflict (id) do nothing;

-- b) the counter continues after the highest number so far ...
select setval(pg_get_serial_sequence('public.recommendations', 'rec_no'),
              greatest((select coalesce(max(rec_no), 0) from public.recommendations), 1),
              (select count(*) from public.recommendations) > 0);

-- c) ... and the rest are numbered oldest first
with logs as (
    select client_id::text as cid, barcode_id, created_at, payload::jsonb as p
    from public.service_logs
    where payload is not null
),
replaced as (
